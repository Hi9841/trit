//! Models that Trit has been run with, and where to get them. Any other
//! checkpoint of a supported family (`MODEL_TYPES`) loads too; these are
//! the ones known to work.

/// One downloadable model.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Known {
    /// Short name; also the folder name under `models/`.
    pub name: &'static str,
    /// Hugging Face repository.
    pub repo: &'static str,
    /// `model_type` of its `config.json`; `vits` and `kokoro` are voices
    /// (text to speech), `g2p` the fallback of the English phonemizer, and
    /// `cleanup` S1-mini.
    pub kind: &'static str,
    /// Languages it writes.
    pub languages: &'static str,
    /// Size of the weights (`model.safetensors`, or the one `file`) in MB.
    pub mb: u32,
    /// The one file that holds the whole model, when Trit reads that file
    /// instead of Hugging Face files: an NVIDIA NeMo archive (`.nemo`) or a
    /// GGUF file (`.gguf`) of a repository that publishes several.
    pub file: Option<&'static str>,
}

